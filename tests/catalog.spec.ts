import { expect, test, type Page } from '@playwright/test'

async function scenario(page: Page, action: string, extra: Record<string, unknown> = {}) {
  const status = await page.evaluate(async ({ action, extra }) => (await fetch('/api/__catalog/scenario', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action, ...extra }) })).status, { action, extra })
  expect(status).toBe(200)
}
async function openFilters(page: Page) {
  const button = page.getByRole('button', { name: 'Abrir filtros' })
  if (await button.isVisible()) { await button.click(); return page.getByRole('dialog', { name: 'Filtros de NFTs' }) }
  return page.locator('.catalog-sidebar')
}
async function closeFilters(page: Page) { const dialog = page.getByRole('dialog', { name: 'Filtros de NFTs' }); if (await dialog.isVisible()) await dialog.getByRole('button', { name: 'Ver resultados' }).click() }
test.beforeEach(async ({ page }) => { await page.goto('/preparation'); await expect(page.getByRole('link', { name: 'Abrir prova de integração' })).toBeVisible(); await scenario(page, 'reset') })

test('malformed URL parameters are validated before reaching the API', async ({ page }) => {
  const rest = page.waitForResponse((response) => response.url().includes('/api/nfts?') && response.status() === 200)
  await page.goto('/?page=-5&sort=bad&collections=unknown&networks=unknown&minPrice=12&maxPrice=1')
  const response = await rest, params = new URL(response.url()).searchParams
  expect(params.get('page')).toBe('1'); expect(params.get('sort')).toBe('recent')
  expect(params.get('collections')).toBe(''); expect(params.get('networks')).toBe('')
  expect(params.get('minPrice')).toBe('1'); expect(params.get('maxPrice')).toBe('12')
  await expect(page.getByLabel('Ordenar NFTs')).toHaveValue('recent')
  await expect(page.getByRole('button', { name: 'Página 1', exact: true })).toHaveAttribute('aria-current', 'page')
})

test('reconnect cancels a slow pre-outage detail snapshot before reconciling', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('nft-emerald-042')).toBeVisible()
  await scenario(page, 'slow', { delay: 3000 })
  await scenario(page, 'disconnect')
  const requested = page.waitForRequest((request) => request.url().endsWith('/api/nfts/emerald-042'))
  await page.getByTestId('nft-emerald-042').getByRole('link', { name: 'Ver Emerald Ape #042' }).click()
  await requested
  await scenario(page, 'change')
  await expect(page.getByTestId('detail-price').filter({ visible: true })).toHaveText('1.29 ETH', { timeout: 10000 })
  expect(await page.evaluate(async () => (await (await fetch('/api/nfts/emerald-042')).json()).nft.version)).toBe(2)
})

test('combined URL filters, sorting, pagination, refresh and history', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.catalog-results .card-name')).toHaveCount(9)
  await page.getByRole('button', { name: 'Página 2', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  const filter = await openFilters(page)
  await filter.getByLabel('Arte digital', { exact: false }).check()
  await filter.getByLabel('Ethereum', { exact: false }).check()
  await closeFilters(page)
  await expect(page).toHaveURL(/page=1/)
  await expect(page).toHaveURL(/digital/)
  await expect(page).toHaveURL(/Ethereum/)
  const descending = page.waitForResponse((response) => response.url().includes('/api/nfts?') && new URL(response.url()).searchParams.get('sort') === 'price-desc' && response.status() === 200)
  await page.getByLabel('Ordenar NFTs').selectOption('price-desc')
  await expect(page).toHaveURL(/price-desc/)
  const names = ((await (await descending).json()) as { items: { name: string }[] }).items.map((item) => item.name)
  await expect(page.locator('.catalog-results .card-name')).toHaveText(names)
  await page.reload()
  await expect(page.locator('.catalog-results .card-name')).toHaveText(names)
  const ascending = page.waitForResponse((response) => response.url().includes('/api/nfts?') && new URL(response.url()).searchParams.get('sort') === 'price-asc' && response.status() === 200)
  await page.getByLabel('Ordenar NFTs').selectOption('price-asc')
  await expect(page).toHaveURL(/price-asc/)
  const ascendingNames = ((await (await ascending).json()) as { items: { name: string }[] }).items.map((item) => item.name)
  await expect(page.locator('.catalog-results .card-name')).toHaveText(ascendingNames)
  await page.goBack()
  await expect(page).toHaveURL(/price-desc/)
  await expect(page.locator('.catalog-results .card-name')).toHaveText(names)
  await page.goForward()
  await expect(page).toHaveURL(/price-asc/)
  await expect(page.locator('.catalog-results .card-name')).toHaveText(ascendingNames)
  const prices = await page.locator('.catalog-results .card-price').allTextContents()
  expect(prices.map((p) => Number.parseFloat(p))).toEqual(prices.map((p) => Number.parseFloat(p)).sort((a, b) => a - b))
})

test('search, empty state, price limits and obsolete response cancellation', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.catalog-results .card-name')).toHaveCount(9)
  const search = page.getByLabel('Buscar NFTs', { exact: true })
  await search.fill('Kurio'); await search.press('Enter')
  await expect(page).toHaveURL(/q=Kurio/)
  await page.getByLabel('Buscar NFTs', { exact: true }).fill('Emerald')
  await page.getByLabel('Buscar NFTs', { exact: true }).press('Enter')
  await expect(page.locator('.catalog-results .card-name')).toHaveText(['Emerald Ape #042'])
  await page.waitForTimeout(1000) // allow the deliberately obsolete mock response to finish
  await expect(page.locator('.catalog-results .card-name')).toHaveText(['Emerald Ape #042'])
  await page.getByLabel('Buscar NFTs', { exact: true }).fill('not-an-nft')
  await page.getByLabel('Buscar NFTs', { exact: true }).press('Enter')
  await expect(page.getByRole('heading', { name: 'Nenhum NFT encontrado' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpar busca e filtros' }).click()
  await expect(page.locator('.catalog-results .card-name')).toHaveCount(9)
  const filters = await openFilters(page)
  await filters.getByLabel('Preço máximo').focus()
  await page.keyboard.press('Home')
  for (let i = 0; i < 98; i++) await page.keyboard.press('ArrowRight')
  await filters.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await closeFilters(page)
  await expect.poll(() => JSON.parse(new URL(page.url()).searchParams.get('maxPrice') ?? 'null')).toBe('1')
  await expect(page.locator('.catalog-results .card-name')).toHaveCount(3)
})

