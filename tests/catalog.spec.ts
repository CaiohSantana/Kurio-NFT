test('Socket.IO updates catalogue/detail, ignores old events, reconciles outage and respects sold-out edition', async ({ page }) => {
  await page.goto('/')
  const card = page.getByTestId('nft-emerald-042')
  await expect(card).toBeVisible()
  await scenario(page, 'change')
  await expect(card.locator('.card-price')).toContainText('1.29 ETH')
  await scenario(page, 'duplicate'); await scenario(page, 'old')
  await expect(card).toHaveAttribute('data-version', '2')
  await card.getByRole('link', { name: 'Ver Emerald Ape #042' }).click()
  await expect(page.getByTestId('detail-price').filter({ visible: true })).toHaveText('1.29 ETH')
  await scenario(page, 'change')
  await expect(page.getByTestId('detail-price').filter({ visible: true })).toHaveText('1.39 ETH')
  await scenario(page, 'disconnect')
  await expect(page.getByText('Conexão interrompida. A reconexão será automática.', { exact: true }).last()).toBeVisible()
  await scenario(page, 'change')
  await expect(page.getByTestId('detail-price').filter({ visible: true })).toHaveText('1.49 ETH')
  await scenario(page, 'sold-out')
  await expect(page.getByText('Edição esgotada.', { exact: true })).toBeVisible()
  expect(await page.evaluate(async () => (await (await fetch('/api/nfts/emerald-042')).json()).nft.version)).toBe(5)
})

test('keyboard focus, drawer/modal, pending actions and responsive overflow', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.catalog-results .card-name')).toHaveCount(9)
  await page.getByLabel('Buscar NFTs', { exact: true }).focus()
  await expect(page.getByLabel('Buscar NFTs', { exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  const filters = await openFilters(page)
  if (await filters.getAttribute('role') === 'dialog' || await page.getByRole('dialog').isVisible()) {
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Abrir filtros' })).toBeFocused()
  }
  const favorites = page.getByRole('button', { name: 'Favoritos', exact: true })
  if (await favorites.isVisible()) { await favorites.click(); await expect(page.getByRole('dialog', { name: 'Funcionalidade indisponível' })).toContainText('Nenhuma operação'); await page.keyboard.press('Escape') }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.goto('/nfts/emerald-042')
  await expect(page.getByTestId('detail-price').filter({ visible: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
